"""自我檢查：cookies 主檔健康檢查（啟動時 + 每天）與每日自我檢查，有問題才私訊擁有者。

cookies 主檔（.env 的 YTDLP_COOKIES）只「讀」，永遠不寫、不交給 yt-dlp：
- 不存在 / 是空的
- 開頭有 yt-dlp 寫回的標頭（"generated by yt-dlp"）→ 曾被 yt-dlp 覆寫，登入工作階段可能已被弱化
- 沒有 LOGIN_INFO
同一種問題 24 小時內只私訊一次（記在 data/selfcheck.json，重啟不會重發）。

每日自我檢查（預設台北時間 09:00，.env 的 SELFCHECK_HOUR 可改；SELFCHECK_HOUR=off 關閉）：
1. cookies 主檔檢查（同上）
2. 用 yt-dlp 實際解析一支固定影片（SELFCHECK_VIDEO），走 ytdl.build_opts() → 只用執行時複本，不碰主檔
3. Discord gateway 延遲
當天跑過就記在 data/selfcheck.json，重啟不會再跑；錯過時間（例如當時在重啟）啟動後補跑一次。
全部正常只寫 log；有任何一項失敗才私訊。
"""
import asyncio
import json
import math
import os
import threading
import time
from datetime import datetime, timedelta, timezone

from .config import PROJECT_ROOT, log

STATE_FILE = os.path.join(PROJECT_ROOT, "data", "selfcheck.json")
REPEAT_AFTER = 24 * 3600            # 同一種問題多久後才再私訊
DEFAULT_HOUR = 9
DEFAULT_VIDEO = "https://www.youtube.com/watch?v=jNQXAC9IVRw"   # Me at the zoo：YouTube 第一支影片，不會被下架
RESOLVE_TIMEOUT = 90
LATENCY_LIMIT = 1.5                 # 秒；超過算異常
YTDLP_HEADER_MARK = "generated by yt-dlp"

try:
    from zoneinfo import ZoneInfo
    TZ = ZoneInfo("Asia/Taipei")
except Exception:
    TZ = timezone(timedelta(hours=8), "Asia/Taipei")

_lock = threading.Lock()


# ---------------- 狀態檔 ----------------
def _load_state():
    try:
        with open(STATE_FILE, encoding="utf-8") as f:
            d = json.load(f)
        return d if isinstance(d, dict) else {}
    except Exception:
        return {}


def _save_state(d):
    tmp = STATE_FILE + ".tmp"
    try:
        os.makedirs(os.path.dirname(STATE_FILE), exist_ok=True)
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False)
        os.replace(tmp, STATE_FILE)
    except Exception as e:
        log.warning(f"[自我檢查] 寫入 {STATE_FILE} 失敗：{e!r}")


# ---------------- cookies 主檔 ----------------
def master_path():
    raw = (os.getenv("YTDLP_COOKIES") or "").strip()
    return os.path.abspath(os.path.expanduser(raw)) if raw else None


def check_cookies(path=None):
    """回傳問題清單 [(kind, 中文說明)]；沒設定 YTDLP_COOKIES（本機開發）回傳 []。只讀檔案名稱與標頭，不讀出任何值。"""
    path = path or master_path()
    if not path:
        return []
    try:
        st = os.stat(path)
    except OSError:
        return [("cookies_missing", "找不到 cookies 主檔（YTDLP_COOKIES 指定的檔案不存在）")]
    if st.st_size == 0:
        return [("cookies_empty", "cookies 主檔是空的")]
    problems = []
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            head = "".join(f.readline() for _ in range(5)).lower()
    except OSError as e:
        return [("cookies_unreadable", f"無法讀取 cookies 主檔：{e.__class__.__name__}")]
    if YTDLP_HEADER_MARK in head:
        problems.append(("cookies_ytdlp_header",
                         "cookies 主檔開頭是 yt-dlp 寫回的標頭（generated by yt-dlp）：曾被 yt-dlp 覆寫，登入工作階段可能已被弱化"))
    from . import ytdl
    if "LOGIN_INFO" not in ytdl.cookie_names(path):
        problems.append(("cookies_no_login_info", "cookies 主檔沒有 LOGIN_INFO（不是已登入的 YouTube 工作階段）"))
    return problems


COOKIE_FIX_HINT = "請用已登入的拋棄式 Google 帳號重新匯出 cookies.txt 覆寫主檔（機器人不會改寫主檔）。"


def _due(state, kind, now):
    last = (state.get("alerts") or {}).get(kind)
    return last is None or now - float(last) >= REPEAT_AFTER


def notify(problems, title, now=None, send=None):
    """problems = [(kind, 說明)]；每種問題 24 小時最多私訊一次。回傳實際私訊的 kind 清單。"""
    if not problems:
        return []
    now = time.time() if now is None else now
    with _lock:
        state = _load_state()
        fresh = [(k, t) for k, t in problems if _due(state, k, now)]
        if not fresh:
            return []
        if send is None:
            from . import alerts
            send = lambda text: alerts.alert("selfcheck:" + ",".join(k for k, _ in fresh), text, force=True)
        lines = [title] + [f"• {t}" for _, t in fresh]
        if any(k.startswith("cookies_") for k, _ in fresh):
            lines.append(COOKIE_FIX_HINT)
        if not send("\n".join(lines)):
            return []                 # bot 還沒就緒等原因沒送出 → 不記錄，下次再試
        al = state.setdefault("alerts", {})
        for k, _ in fresh:
            al[k] = now
        _save_state(state)
    return [k for k, _ in fresh]


def startup_cookie_check():
    """on_ready 第一次時呼叫"""
    problems = check_cookies()
    if problems:
        log.warning("[自我檢查] cookies 主檔有問題：" + "；".join(t for _, t in problems))
        notify(problems, "⚠️ 啟動檢查：YouTube cookies 主檔有問題")
    return problems


# ---------------- 每日自我檢查 ----------------
def _hour():
    raw = (os.getenv("SELFCHECK_HOUR") or "").strip().lower()
    if raw in ("off", "no", "false", "-1"):
        return None
    try:
        h = int(raw) if raw else DEFAULT_HOUR
        return h if 0 <= h <= 23 else DEFAULT_HOUR
    except ValueError:
        return DEFAULT_HOUR


def today(now=None):
    return datetime.fromtimestamp(time.time() if now is None else now, TZ).strftime("%Y-%m-%d")


def seconds_until_due(now=None, hour=DEFAULT_HOUR, last_day=None):
    """距離下一次該跑還有幾秒；今天還沒跑且已過時間 → 0（補跑）"""
    now = time.time() if now is None else now
    dt = datetime.fromtimestamp(now, TZ)
    slot = dt.replace(hour=hour, minute=0, second=0, microsecond=0)
    if last_day != dt.strftime("%Y-%m-%d") and dt >= slot:
        return 0.0
    if dt >= slot:
        slot = slot + timedelta(days=1)
    return max(0.0, (slot - dt).total_seconds())


def _resolve_test():
    from . import prefetch
    video = (os.getenv("SELFCHECK_VIDEO") or "").strip() or DEFAULT_VIDEO
    res = prefetch.extract_stream(video)     # build_opts() → cookies 執行時複本
    if not res.get("url"):
        raise RuntimeError("解析結果沒有串流網址")
    return res


def _latency():
    from .bot import client
    try:
        return float(client.latency)
    except Exception:
        return float("inf")


async def run_daily(now=None):
    """跑一次每日檢查。回傳 {"ok": bool, "problems": [...], "resolve_s": float|None, "latency_ms": int|None}"""
    problems = list(check_cookies())
    resolve_s = None
    t0 = time.monotonic()
    try:
        loop = asyncio.get_running_loop()
        await asyncio.wait_for(loop.run_in_executor(None, _resolve_test), RESOLVE_TIMEOUT)
        resolve_s = round(time.monotonic() - t0, 2)
    except Exception as e:
        from . import ytdl
        msg = "YouTube 要求機器人驗證（cookies 可能失效）" if ytdl.is_bot_check(e) else str(e)[:200]
        if isinstance(e, asyncio.TimeoutError):
            msg = f"超過 {RESOLVE_TIMEOUT} 秒沒有回應"
        problems.append(("resolve_fail", f"yt-dlp 解析測試影片失敗：{msg}"))
    lat = _latency()
    latency_ms = None if not math.isfinite(lat) else int(lat * 1000)
    if latency_ms is None or lat > LATENCY_LIMIT:
        problems.append(("latency", f"Discord 連線延遲異常：{'未連線' if latency_ms is None else f'{latency_ms} ms'}"))
    with _lock:
        st = _load_state()
        st["last_day"] = today(now)
        st["last_result"] = {"ts": time.time() if now is None else now, "ok": not problems,
                             "problems": [k for k, _ in problems], "resolve_s": resolve_s, "latency_ms": latency_ms}
        _save_state(st)
    if problems:
        log.warning("[自我檢查] 每日檢查發現問題：" + "；".join(t for _, t in problems))
        notify(problems, "⚠️ 每日自我檢查發現問題", now=now)
    else:
        log.info(f"[自我檢查] 每日檢查正常：cookies OK、解析 {resolve_s} 秒、延遲 {latency_ms} ms")
    return {"ok": not problems, "problems": [k for k, _ in problems], "resolve_s": resolve_s, "latency_ms": latency_ms}


async def loop_task():
    while True:
        hour = _hour()
        if hour is None:
            return
        wait = seconds_until_due(hour=hour, last_day=_load_state().get("last_day"))
        if wait > 0:
            await asyncio.sleep(min(wait, 3600))   # 最多睡 1 小時再重算（電腦睡眠 / 時鐘調整也不會錯過太久）
            continue
        try:
            await run_daily()
        except Exception as e:
            log.warning(f"[自我檢查] 每日檢查執行失敗：{e!r}")
            with _lock:
                st = _load_state()
                st["last_day"] = today()
                _save_state(st)
        await asyncio.sleep(60)


_started = [False]


def start(client):
    if not _started[0]:
        _started[0] = True
        client.loop.create_task(loop_task())
