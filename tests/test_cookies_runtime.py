"""cookies 主檔不可被 yt-dlp 寫回；缺少 LOGIN_INFO/SID 時要警告。"""
import os
import tempfile
import time
import unittest
from unittest import mock

os.environ.setdefault("DISCORD_TOKEN", "test-dummy")
import sys
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from musicbot import ytdl, sysinfo  # noqa: E402


def _jar(path, names, header="# Netscape HTTP Cookie File\n"):
    lines = [header]
    for name in names:
        # 名稱以外的欄位是假資料，測試不讀值
        lines.append(f".youtube.com\tTRUE\t/\tTRUE\t0\t{name}\tx\n")
    with open(path, "w", encoding="utf-8") as f:
        f.writelines(lines)


class CookieRuntime(unittest.TestCase):
    def setUp(self):
        ytdl.reset_cookie_runtime()
        self.tmp = tempfile.TemporaryDirectory()
        self.master = os.path.join(self.tmp.name, "cookies.txt")

    def tearDown(self):
        ytdl.reset_cookie_runtime()
        self.tmp.cleanup()

    def _opts(self, **env):
        base = {"YTDLP_COOKIES": self.master, "YTDLP_COOKIES_FROM_BROWSER": ""}
        base.update(env)
        with mock.patch.dict(os.environ, base, clear=False):
            return ytdl.build_opts({"quiet": True})

    def test_runtime_path_is_not_master(self):
        _jar(self.master, ["LOGIN_INFO", "SID"])
        out = self._opts()
        self.assertNotEqual(out["cookiefile"], self.master)
        self.assertTrue(os.path.isfile(out["cookiefile"]))
        with open(self.master, encoding="utf-8") as f:
            self.assertIn("LOGIN_INFO", f.read())

    def test_writing_runtime_does_not_change_master(self):
        _jar(self.master, ["LOGIN_INFO", "SID"])
        with open(self.master, "rb") as fh: before = fh.read()
        mtime = os.path.getmtime(self.master)
        out = self._opts()
        # 模擬 yt-dlp 把弱化後的 cookiejar 寫回 cookiefile
        with open(out["cookiefile"], "w", encoding="utf-8") as f:
            f.write("# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n")
            f.write(".youtube.com\tTRUE\t/\tTRUE\t0\tPREF\tx\n")
        time.sleep(0.02)
        with open(self.master, "rb") as fh: self.assertEqual(fh.read(), before)
        self.assertEqual(os.path.getmtime(self.master), mtime)
        self.assertTrue(ytdl.has_session_cookies(self.master))
        self.assertFalse(ytdl.has_session_cookies(out["cookiefile"]))

    def test_session_ok_login_info_or_sid(self):
        _jar(self.master, ["PREF", "LOGIN_INFO"])
        self.assertTrue(ytdl.has_session_cookies(self.master))
        _jar(self.master, ["SID"])
        self.assertTrue(ytdl.has_session_cookies(self.master))
        _jar(self.master, ["__Secure-1PSID", "YSC"])
        self.assertTrue(ytdl.has_session_cookies(self.master))
        _jar(self.master, ["SAPISID"])
        self.assertTrue(ytdl.has_session_cookies(self.master))
        _jar(self.master, ["PREF", "VISITOR_INFO1_LIVE", "__Secure-3PSID"])
        self.assertFalse(ytdl.has_session_cookies(self.master))

    def test_warns_when_session_missing(self):
        _jar(self.master, ["PREF", "__Secure-3PSID"])
        with self.assertLogs("musicbot", "WARNING") as cm:
            self._opts()
        self.assertTrue(any("LOGIN_INFO" in x or "SID" in x for x in cm.output))
        st = self._status()
        self.assertTrue(st["configured"])
        self.assertFalse(st["session_ok"])
        self.assertIn("LOGIN_INFO", st["warning"] or "")

    def test_status_ok_when_session_present(self):
        _jar(self.master, ["LOGIN_INFO", "SID"])
        self._opts()
        st = self._status()
        self.assertTrue(st["configured"])
        self.assertTrue(st["session_ok"])
        self.assertIsNone(st["warning"])
        self.assertNotIn("path", st)
        blob = str(st)
        self.assertNotIn(self.master, blob)

    def test_recopy_when_master_changes(self):
        _jar(self.master, ["PREF"])
        first = self._opts()["cookiefile"]
        time.sleep(0.05)
        _jar(self.master, ["LOGIN_INFO", "SID"])
        os.utime(self.master, None)
        second = self._opts()
        self.assertEqual(second["cookiefile"], first)  # 覆寫同一個暫存檔
        self.assertTrue(ytdl.has_session_cookies(first))
        st = self._status()
        self.assertTrue(st["session_ok"])

    def test_missing_file_ignored(self):
        with mock.patch.dict(os.environ, {"YTDLP_COOKIES": os.path.join(self.tmp.name, "nope.txt"),
                                          "YTDLP_COOKIES_FROM_BROWSER": ""}):
            out = ytdl.build_opts({})
        self.assertNotIn("cookiefile", out)

    def test_sysinfo_includes_cookies(self):
        _jar(self.master, ["LOGIN_INFO"])
        with mock.patch.dict(os.environ, {"YTDLP_COOKIES": self.master, "YTDLP_COOKIES_FROM_BROWSER": ""}):
            ytdl.warn_cookie_quality()
            data = sysinfo.status()
        self.assertIn("cookies", data)
        self.assertTrue(data["cookies"]["session_ok"])

    def _status(self):
        with mock.patch.dict(os.environ, {"YTDLP_COOKIES": self.master, "YTDLP_COOKIES_FROM_BROWSER": ""}):
            return ytdl.cookie_status()


if __name__ == "__main__":
    unittest.main()
