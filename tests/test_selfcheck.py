import asyncio
import os
import pathlib
import shutil
import sys
import tempfile
import unittest
from datetime import datetime
from unittest import mock

os.environ.setdefault("DISCORD_TOKEN", "test-dummy")
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from musicbot import selfcheck  # noqa: E402

GOOD = ("# Netscape HTTP Cookie File\n"
        ".youtube.com\tTRUE\t/\tTRUE\t0\tLOGIN_INFO\tx\n"
        ".youtube.com\tTRUE\t/\tTRUE\t0\tSID\tx\n")
YTDLP = ("# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n\n"
         ".youtube.com\tTRUE\t/\tTRUE\t0\tLOGIN_INFO\tx\n")
NO_LOGIN = "# Netscape HTTP Cookie File\n.youtube.com\tTRUE\t/\tTRUE\t0\tVISITOR_INFO1_LIVE\tx\n"


def ts(y, mo, d, h, mi=0):
    return datetime(y, mo, d, h, mi, tzinfo=selfcheck.TZ).timestamp()


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp, True)
        p = mock.patch.object(selfcheck, "STATE_FILE", os.path.join(self.tmp, "selfcheck.json"))
        p.start()
        self.addCleanup(p.stop)
        self.cookie = os.path.join(self.tmp, "cookies.txt")

    def write(self, text):
        with open(self.cookie, "w", encoding="utf-8") as f:
            f.write(text)
        return self.cookie

    def kinds(self, path):
        return [k for k, _ in selfcheck.check_cookies(path)]


class CookieCheckTest(Base):
    def test_good(self):
        self.assertEqual(self.kinds(self.write(GOOD)), [])

    def test_missing_and_empty(self):
        self.assertEqual(self.kinds(self.cookie), ["cookies_missing"])
        self.assertEqual(self.kinds(self.write("")), ["cookies_empty"])

    def test_ytdlp_header(self):
        self.assertEqual(self.kinds(self.write(YTDLP)), ["cookies_ytdlp_header"])

    def test_no_login_info(self):
        self.assertEqual(self.kinds(self.write(NO_LOGIN)), ["cookies_no_login_info"])

    def test_unset_env_is_ok(self):
        with mock.patch.dict(os.environ, {"YTDLP_COOKIES": ""}):
            self.assertEqual(selfcheck.check_cookies(), [])
        with mock.patch.dict(os.environ, {"YTDLP_COOKIES": self.write(YTDLP)}):
            self.assertEqual([k for k, _ in selfcheck.check_cookies()], ["cookies_ytdlp_header"])

    def test_read_only_and_no_values_in_text(self):
        self.write(GOOD.replace("\tx\n", "\tSECRETVALUE\n") + "# This file is generated by yt-dlp\n")
        before = pathlib.Path(self.cookie).read_bytes(), os.stat(self.cookie).st_mtime_ns
        probs = selfcheck.check_cookies(self.cookie)
        self.assertEqual(before, (pathlib.Path(self.cookie).read_bytes(), os.stat(self.cookie).st_mtime_ns))  # 沒有被改寫
        self.assertNotIn("SECRETVALUE", repr(probs))


class NotifyTest(Base):
    def test_rate_limit_24h_survives_restart(self):
        sent = []
        send = lambda t: sent.append(t) or True
        p = [("cookies_ytdlp_header", "標頭")]
        self.assertEqual(selfcheck.notify(p, "T", now=1000, send=send), ["cookies_ytdlp_header"])
        self.assertIn(selfcheck.COOKIE_FIX_HINT, sent[0])
        # 「重啟」：狀態只在檔案裡，重新讀取仍然記得
        self.assertEqual(selfcheck.notify(p, "T", now=1000 + 3600, send=send), [])
        self.assertEqual(selfcheck.notify(p, "T", now=1000 + 24 * 3600 - 1, send=send), [])
        self.assertEqual(len(sent), 1)
        self.assertEqual(selfcheck.notify(p, "T", now=1000 + 24 * 3600, send=send), ["cookies_ytdlp_header"])
        self.assertEqual(len(sent), 2)

    def test_distinct_problems_independent(self):
        sent = []
        send = lambda t: sent.append(t) or True
        selfcheck.notify([("cookies_ytdlp_header", "a")], "T", now=1000, send=send)
        r = selfcheck.notify([("cookies_ytdlp_header", "a"), ("cookies_no_login_info", "b")], "T", now=2000, send=send)
        self.assertEqual(r, ["cookies_no_login_info"])     # 只有新的那種
        self.assertNotIn("• a", sent[1])

    def test_not_recorded_when_send_fails(self):
        p = [("latency", "x")]
        self.assertEqual(selfcheck.notify(p, "T", now=1000, send=lambda t: False), [])   # bot 未就緒
        self.assertEqual(selfcheck.notify(p, "T", now=1001, send=lambda t: True), ["latency"])

    def test_startup_check_uses_alerts(self):
        with mock.patch.dict(os.environ, {"YTDLP_COOKIES": self.write(NO_LOGIN)}), \
             mock.patch("musicbot.alerts.alert", return_value=True) as al:
            self.assertEqual([k for k, _ in selfcheck.startup_cookie_check()], ["cookies_no_login_info"])
            self.assertEqual(al.call_count, 1)
            self.assertTrue(al.call_args.kwargs.get("force"))
            selfcheck.startup_cookie_check()                # 立刻再重啟 → 不重發
            self.assertEqual(al.call_count, 1)


class ScheduleTest(unittest.TestCase):
    def test_before_hour(self):
        self.assertEqual(selfcheck.seconds_until_due(ts(2026, 11, 14, 8, 30), 9, None), 1800)

    def test_catch_up_after_hour(self):
        self.assertEqual(selfcheck.seconds_until_due(ts(2026, 11, 14, 15, 0), 9, "2026-11-13"), 0)

    def test_already_ran_today(self):
        self.assertEqual(selfcheck.seconds_until_due(ts(2026, 11, 14, 15, 0), 9, "2026-11-14"), 18 * 3600)

    def test_before_hour_ran_yesterday(self):
        self.assertEqual(selfcheck.seconds_until_due(ts(2026, 11, 14, 0, 0), 9, "2026-11-13"), 9 * 3600)

    def test_hour_env(self):
        for raw, want in (("", 9), ("7", 7), ("off", None), ("-1", None), ("x", 9), ("30", 9)):
            with mock.patch.dict(os.environ, {"SELFCHECK_HOUR": raw}):
                self.assertEqual(selfcheck._hour(), want, raw)

    def test_today_taipei(self):
        self.assertEqual(selfcheck.today(ts(2026, 11, 14, 0, 30)), "2026-11-14")   # UTC 還是 11/13


class RunDailyTest(Base):
    def run_daily(self, resolve=None, latency=0.08, now=None):
        resolve = resolve or (lambda: {"url": "https://x"})
        with mock.patch.dict(os.environ, {"YTDLP_COOKIES": self.cookie}), \
             mock.patch.object(selfcheck, "_resolve_test", resolve), \
             mock.patch.object(selfcheck, "_latency", lambda: latency), \
             mock.patch("musicbot.alerts.alert", return_value=True) as al:
            r = asyncio.run(selfcheck.run_daily(now=now))
        return r, al

    def test_all_ok_no_dm(self):
        self.write(GOOD)
        r, al = self.run_daily(now=ts(2026, 11, 14, 9))
        self.assertTrue(r["ok"])
        self.assertEqual(r["latency_ms"], 80)
        al.assert_not_called()
        st = selfcheck._load_state()
        self.assertEqual(st["last_day"], "2026-11-14")      # 重啟後不會再跑
        self.assertTrue(st["last_result"]["ok"])

    def test_resolve_fail_dms(self):
        self.write(GOOD)

        def boom():
            raise RuntimeError("ERROR: Sign in to confirm you're not a bot")
        r, al = self.run_daily(resolve=boom, now=ts(2026, 11, 14, 9))
        self.assertFalse(r["ok"])
        self.assertEqual(r["problems"], ["resolve_fail"])
        al.assert_called_once()
        self.assertIn("機器人驗證", al.call_args.args[1])

    def test_latency_and_cookie_problems(self):
        self.write(YTDLP)
        r, al = self.run_daily(latency=float("inf"), now=ts(2026, 11, 14, 9))
        self.assertEqual(r["problems"], ["cookies_ytdlp_header", "latency"])
        self.assertIsNone(r["latency_ms"])
        al.assert_called_once()
        r, al = self.run_daily(latency=float("inf"), now=ts(2026, 11, 14, 10))
        al.assert_not_called()                              # 同一天再跑：24 小時內不重發

    def test_resolve_uses_runtime_copy_not_master(self):
        from musicbot import prefetch
        self.write(GOOD)
        seen = {}

        class YDL:
            def __init__(s, opts): seen.update(opts)
            def __enter__(s): return s
            def __exit__(s, *a): return False
            def extract_info(s, url, download=False):
                seen["url"] = url
                return {"url": "https://rr.googlevideo.com/x", "id": "jNQXAC9IVRw"}
        before = pathlib.Path(self.cookie).read_bytes()
        with mock.patch.dict(os.environ, {"YTDLP_COOKIES": self.cookie, "SELFCHECK_VIDEO": ""}), \
             mock.patch.object(prefetch.yt_dlp, "YoutubeDL", YDL):
            selfcheck._resolve_test()
        self.assertEqual(seen["url"], selfcheck.DEFAULT_VIDEO)
        self.assertIn("cookiefile", seen)
        self.assertNotEqual(os.path.abspath(seen["cookiefile"]), os.path.abspath(self.cookie))
        self.assertEqual(before, pathlib.Path(self.cookie).read_bytes())


